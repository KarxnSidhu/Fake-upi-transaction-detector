async function runFrontendChecks() {
  const $ = id => document.getElementById(id);
  const results = [];
  const ok = (name, condition) => { results.push({name, passed: Boolean(condition)}); if (!condition) throw new Error(name); };
  const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
  const settle = async fn => { for(let i=0;i<60;i++){if(fn()) return;await pause(25);}throw Error('UI did not settle'); };
  await settle(() => $('service-label').textContent.includes('online'));
  ok('initial scan disabled', $('analyse-button').disabled);
  ok('initial layout does not overflow', document.documentElement.scrollWidth <= innerWidth);
  ok('API fixture stats rendered', $('stat-total').textContent === '3');
  const canvas = document.createElement('canvas'); canvas.width=540;canvas.height=1080;
  const ctx=canvas.getContext('2d');ctx.fillStyle='#f5f5f5';ctx.fillRect(0,0,540,1080);ctx.fillStyle='#111';ctx.font='24px Arial';ctx.fillText('SYNTHETIC TEST',40,160);ctx.fillText('NOT A PAYMENT',40,210);
  const blob=await new Promise(resolve=>canvas.toBlob(resolve,'image/png'));
  const file=new File([blob],'test-screenshot-with-a-very-long-name-for-mobile-layout-checks-1234567890.png',{type:'image/png'});
  const choose=async f=>{const dt=new DataTransfer();dt.items.add(f);$('file-input').files=dt.files;$('file-input').dispatchEvent(new Event('change',{bubbles:true}));await pause(75);};
  await choose(new File(['x'],'invalid.txt',{type:'text/plain'}));
  ok('unsupported format blocked', !$('upload-error').hidden && $('analyse-button').disabled);
  await choose(new File([],'empty.png',{type:'image/png'}));
  ok('empty image blocked', $('upload-error').textContent.includes('empty'));
  await choose(new File([new Uint8Array(8*1024*1024+1)],'large.png',{type:'image/png'}));
  ok('oversized image blocked', $('upload-error').textContent.includes('8 MB'));
  await choose(new File(['not a png'],'broken.png',{type:'image/png'}));
  ok('damaged image blocked', $('upload-error').textContent.includes('could not be opened'));
  await choose(file);await settle(() => !$('analyse-button').disabled);
  ok('preview decodes and enables scan', !$('preview-wrap').hidden);
  window.__apiMode='slow';$('analyse-button').click();await pause(30);
  ok('loading state visible', !$('loading-state').hidden);
  ok('inputs locked during scan', $('upload-controls').disabled && $('analyse-button').disabled);
  const dt=new DataTransfer();dt.items.add(new File([blob],'other.png',{type:'image/png'}));$('drop-zone').dispatchEvent(new DragEvent('drop',{bubbles:true,dataTransfer:dt}));
  ok('drop cannot replace an in-flight file', $('file-name').textContent===file.name);
  $('cancel-button').click();await settle(() => !$('upload-controls').disabled);
  ok('cancel warning and recovery', $('upload-error').textContent.includes('server may still save') && !$('analyse-button').disabled);
  window.__apiMode='error';$('analyse-button').click();await settle(() => !$('upload-controls').disabled);
  ok('server error rendered', $('upload-error').textContent.includes('Test server rejected'));
  window.__apiMode='malformed';$('analyse-button').click();await settle(() => !$('upload-controls').disabled);
  ok('malformed response rejected', $('upload-error').textContent.includes('incomplete analysis'));
  window.__apiMode='partial';$('analyse-button').click();await settle(() => !$('result-content').hidden);
  ok('partial verdict and missing check', !$('partial-notice').hidden && document.querySelectorAll('.check-row.unavailable').length===1);
  ok('all nine checks rendered', document.querySelectorAll('.check-row').length===9);
  ok('unsafe OCR text not executed', $('ocr-text').querySelector('img')===null && $('ocr-text').textContent.includes('<img'));
  ok('long filename and transaction ID fit', document.documentElement.scrollWidth<=innerWidth);
  const radio=document.querySelector('input[value="PhonePe"]');radio.checked=true;radio.dispatchEvent(new Event('change',{bubbles:true}));
  ok('changing app clears stale report', $('result-content').hidden);
  window.__apiMode='missing';$('analyse-button').click();await settle(()=>!$('result-content').hidden);
  ok('absent check data is not a pass', document.querySelectorAll('.check-row.unavailable').length===9 && !$('partial-notice').hidden);
  window.__apiMode='suspicious';$('analyse-button').click();await settle(()=>!$('upload-controls').disabled);
  ok('suspicious verdict displayed', $('verdict-card').classList.contains('suspicious'));
  window.__apiMode='clear';$('analyse-button').click();await settle(()=>!$('upload-controls').disabled);
  ok('complete result displayed honestly', $('verdict-label').textContent==='No obvious anomaly' && $('verdict-caption').textContent.includes('not proof'));
  const originalClick=HTMLAnchorElement.prototype.click;const downloads=[];
  HTMLAnchorElement.prototype.click=function(){if(this.download)downloads.push(this.download);else originalClick.call(this);};
  $('download-report').click();ok('report download triggered',downloads.some(name=>name.endsWith('.json')));
  location.hash='history';await pause(60);await settle(()=>$('history-summary').textContent.includes('3 recent'));
  ok('history navigation', !$('history-view').hidden && $('scanner-view').hidden);
  $('history-search').value='PhonePe';$('history-search').dispatchEvent(new Event('input'));
  ok('history search', $('history-body').rows.length===1 && $('history-body').textContent.includes('PhonePe'));
  $('history-search').value='';$('history-search').dispatchEvent(new Event('input'));$('history-filter').value='suspicious';$('history-filter').dispatchEvent(new Event('change'));
  ok('verdict filtering', $('history-body').rows.length===1 && $('history-body').textContent.includes('Suspicious'));
  $('export-history').click();ok('filtered CSV export triggered',downloads.includes('upi-shield-history.csv'));
  HTMLAnchorElement.prototype.click=originalClick;
  $('history-search').value='no-match';$('history-search').dispatchEvent(new Event('input'));
  ok('no matches state', $('history-body').textContent.includes('No matching scans') && $('export-history').disabled);
  window.__historyError=true;$('refresh-history').click();await settle(()=>!$('refresh-history').disabled);
  ok('history error and retry', $('history-body').textContent.includes('Retry loading history'));
  window.__historyError=false;$('refresh-history').click();await settle(()=>!$('refresh-history').disabled);
  window.__healthError=true;$('service-button').click();await settle(()=>!$('service-button').disabled);
  ok('offline status explicit', $('service-label').textContent.includes('offline'));
  window.__healthError=false;$('service-button').click();await settle(()=>!$('service-button').disabled);
  ok('service retry recovers', $('service-label').textContent.includes('online'));
  location.hash='guide';await pause(50);ok('guide navigation', !$('guide-view').hidden);
  ok('camera uses native capture with browse fallback', $('camera-input').getAttribute('capture')==='environment' && Boolean($('browse-button')));
  location.hash='scanner';await pause(50);$('new-scan').click();ok('new scan resets selection', $('analyse-button').disabled && $('preview-wrap').hidden);
  ok('all main actions have 44px targets', ['browse-button','camera-button','analyse-button','service-button'].every(id=>$(id).getBoundingClientRect().height>=44));
  $('browse-button').focus();ok('keyboard focus style defined', getComputedStyle($('browse-button')).outlineStyle !== 'none');
  return {viewport:`${innerWidth}x${innerHeight}`,results};
}

module.exports = runFrontendChecks;

